function today(): string {
  return new Date().toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}

// ── 1. DPIA screening ────────────────────────────────────────────────────

export function generateDpia(input: ReturnType<typeof toDpiaInput>): string {
  const { systemName, purpose, dataTypes, automatedDecision, systematicMonitoring, largeScale, safeguards } = input;

  const name = systemName.trim() || "[System / process name]";
  const purposeText = purpose.trim() || "[Describe what the AI system does and why]";

  const dataTypeLines = dataTypes.size
    ? [...dataTypes].map((v) => `- ${PROGRAM_DATA_TYPES.find((d) => d.value === v)?.label}`).join("\n")
    : "- [No data types selected yet]";

  const safeguardLines = safeguards.size
    ? [...safeguards].map((v) => `- ${PROGRAM_SAFEGUARDS.find((s) => s.value === v)?.label}`).join("\n")
    : "- None recorded yet — this is the section most likely to draw a regulator's attention";

  const hasSpecialCategory = dataTypes.has("special_category") || dataTypes.has("children") || dataTypes.has("criminal");
  const dpiaRequired = hasSpecialCategory || automatedDecision || systematicMonitoring || (largeScale && dataTypes.size > 0 && !dataTypes.has("none"));

  const riskFactors: string[] = [];
  if (hasSpecialCategory) riskFactors.push("Processes special category, children's, or criminal offence data — Article 9/10 UK GDPR applies");
  if (automatedDecision) riskFactors.push("Involves automated decision-making with legal or similarly significant effect on individuals — Article 22 UK GDPR applies");
  if (systematicMonitoring) riskFactors.push("Involves systematic monitoring of individuals");
  if (largeScale) riskFactors.push("Processing is large scale");
  if (!riskFactors.length) riskFactors.push("No high-risk factors selected — screening below is based on current answers only");

  return `DATA PROTECTION IMPACT ASSESSMENT — SCREENING
Generated by Red Flag AI Pro, ${today()}

1. SYSTEM / PROCESS
${name}

2. DESCRIPTION OF PROCESSING
${purposeText}

3. DATA TYPES PROCESSED
${dataTypeLines}

4. RISK FACTORS IDENTIFIED
${riskFactors.map((r) => `- ${r}`).join("\n")}

5. NECESSITY & PROPORTIONALITY
Is there a less intrusive way to achieve the same purpose? [Answer before finalizing — this question has to be answered, not skipped, for the assessment to be genuine rather than a formality.]

6. SAFEGUARDS IN PLACE
${safeguardLines}

7. SCREENING OUTCOME
${dpiaRequired
  ? "A full DPIA is required under UK GDPR Article 35(3) before this processing begins or continues. At least one high-risk factor above triggers the requirement — this is not optional."
  : "Based on the factors selected, a full DPIA is not automatically required under Article 35(3). Completing one anyway is still good practice, and this screening should be revisited if the processing changes."}

8. SIGN-OFF
Assessed by: ______________________     Date: ______________
Reviewed by (DPO or equivalent): ______________________     Date: ______________

This is a screening document, not legal advice. It follows the ICO's own DPIA screening checklist structure. If the outcome above says a full DPIA is required, complete one before processing begins — the ICO's full DPIA template is linked below.`;
}

// ── 2. FRIA draft ────────────────────────────────────────────────────────

