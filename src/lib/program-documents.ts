// ── Bundle: run all six from one shared intake ──────────────────────────

export interface ProgramDocumentBundle {
  dpia: string;
  fria: string;
  ai_use_policy: string;
  incident_checklist: string;
  monitoring_plan: string;
  documentation: string;
}

// Single source of truth for each document's human label and display order,
// used by the enhancement layer, the seal record, and the delivery page so
// none of them can drift out of step with each other.
export const DOCUMENT_LABELS: { key: keyof ProgramDocumentBundle; label: string }[] = [
  { key: "dpia", label: "Data Protection Impact Assessment screening" },
  { key: "fria", label: "Fundamental Rights Impact Assessment draft" },
  { key: "ai_use_policy", label: "AI Acceptable Use Policy draft" },
  { key: "incident_checklist", label: "Incident reporting checklist" },
  { key: "monitoring_plan", label: "Post market monitoring plan draft" },
  { key: "documentation", label: "Annex IV technical documentation draft" },
];

export function generateAllProgramDocuments(intake: {
  companyName: string;
  systemName: string;
  purpose: string;
  architecture: string;
  primaryJurisdiction: string;
  dataTypes: string[];
  dataSources: string;
  automatedDecision: boolean;
  systematicMonitoring: boolean;
  largeScale: boolean;
  safeguards: string[];
  oversightMeasures: string;
  mitigationMeasures: string;
  testing: string;
  limitations: string;
  affectedParties: string;
  usagePeriod: string;
  specificRisks: string;
  metrics: string;
  reviewCadence: string;
  thresholds: string;
  correctiveAction: string;
  recordKeeping: string;
  prohibitedUses: string;
  dataRules: string;
  approvalProcess: string;
  reportingChannel: string;
}): ProgramDocumentBundle {
  // Cast is safe: the intake read back from Supabase jsonb has the same
  // shape as ProgramIntake, just without the branded union types enforced —
  // the mapper functions only ever read known string/boolean/array fields.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const i = intake as any;

  return {
    dpia: generateDpia(toDpiaInput(i)),
    fria: generateFria(toFriaInput(i)),
    ai_use_policy: generateAiUsePolicy(toAiUsePolicyInput(i)),
    incident_checklist: generateIncidentChecklist(toIncidentChecklistInput(i)),
    monitoring_plan: generateMonitoringPlan(toMonitoringPlanInput(i)),
    documentation: generateDocumentation(toDocumentationInput(i)),
  };
}
