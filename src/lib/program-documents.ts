const ARCHITECTURE_TYPES: Record<string, string> = {
  rule_based: "Rule-based / decision logic (no machine learning)",
  classic_ml: "Classic machine learning (regression, classifier, etc.)",
  llm: "Large language model, used directly or fine-tuned",
  hybrid: "Hybrid — a mix of the above",
  // The program mapper passes through the intake's own architecture values
  // (third_party_api / fine_tuned / in_house / hybrid), which don't share
  // the free tool's vocabulary one for one — mapped to the closest label.
  third_party_api: "Large language model, used directly or fine-tuned",
  fine_tuned: "Large language model, used directly or fine-tuned",
  in_house: "Classic machine learning (regression, classifier, etc.)",
};

